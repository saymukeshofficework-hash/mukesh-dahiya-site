// Helper functions
export function getAllScienceClasses(): ScienceClassMeta[] {
  return scienceClasses
}

export function getScienceClass(classSlug: string): ScienceClassMeta | undefined {
  return scienceClasses.find((c) => c.classSlug === classSlug)
}

export function getScienceNotesForClass(classSlug: string, subjectSlug?: string): ScienceNote[] {
  return scienceNotes.filter((n) => {
    if (n.classSlug !== classSlug) return false
    if (subjectSlug && n.subjectSlug !== subjectSlug) return false
    return true
  }).sort((a, b) => a.chapterNumber - b.chapterNumber)
}

export function getScienceNote(classSlug: string, chapterSlug: string): ScienceNote | undefined {
  return scienceNotes.find((n) => n.classSlug === classSlug && n.slug === chapterSlug)
}

export function getAdjacentScienceNotes(classSlug: string, chapterSlug: string): { prev?: ScienceNote; next?: ScienceNote } {
  const classNotes = getScienceNotesForClass(classSlug)
  const idx = classNotes.findIndex((n) => n.slug === chapterSlug)
  if (idx === -1) return {}
  return {
    prev: idx > 0 ? classNotes[idx - 1] : undefined,
    next: idx < classNotes.length - 1 ? classNotes[idx + 1] : undefined,
  }
}

export function getRelatedScienceNotes(note: ScienceNote): ScienceNote[] {
  return scienceNotes
    .filter((n) => n.id !== note.id && (n.classSlug === note.classSlug || n.subjectSlug === note.subjectSlug))
    .slice(0, 3)
}

export function countNotesForClass(classSlug: string, subjectSlug?: string): number {
  return getScienceNotesForClass(classSlug, subjectSlug).length
}
